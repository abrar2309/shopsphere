
package com.abrar.shopsphere.service;

import com.abrar.shopsphere.dto.AddressRequestDTO;
import com.abrar.shopsphere.dto.AddressResponseDTO;
import com.abrar.shopsphere.entity.Address;
import com.abrar.shopsphere.entity.User;
import com.abrar.shopsphere.repository.AddressRepository;
import com.abrar.shopsphere.repository.UserRepository;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;

import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AddressServiceTest {

    @Mock
    private AddressRepository addressRepository;

    @Mock
    private UserRepository userRepository;

    @InjectMocks
    private AddressService addressService;

    private User user;

    @BeforeEach
    void setUp() {
        user = new User();
        user.setId(1L);
        user.setEmail("customer@example.com");
        user.setFirstName("Test");
    }

    private AddressRequestDTO createRequest(Boolean isDefault) {

        AddressRequestDTO request = new AddressRequestDTO();

        request.setLabel("Home");
        request.setRecipientName("Test Customer");
        request.setPhoneNumber("9876543210");
        request.setAddressLine1("123 Main Street");
        request.setAddressLine2("Apartment 4");
        request.setCity("Bengaluru");
        request.setState("Karnataka");
        request.setPostalCode("560001");
        request.setCountry("India");
        request.setIsDefault(isDefault);

        return request;
    }

    private Address createAddress(Long id, boolean isDefault) {

        Address address = new Address();

        address.setUser(user);
        address.setLabel("Home");
        address.setRecipientName("Test Customer");
        address.setPhoneNumber("9876543210");
        address.setAddressLine1("123 Main Street");
        address.setCity("Bengaluru");
        address.setState("Karnataka");
        address.setPostalCode("560001");
        address.setCountry("India");
        address.setDefault(isDefault);

        // The ID is normally generated by the database.
        // Reflection is unnecessary for these tests; use a saved
        // entity returned by the repository when an ID is required.
        return address;
    }

    private void mockAuthenticatedUser() {

        when(userRepository.findByEmail("customer@example.com"))
                .thenReturn(Optional.of(user));

        when(userRepository.findByIdForUpdate(1L))
                .thenReturn(Optional.of(user));
    }

    @Test
    void firstAddressShouldAutomaticallyBecomeDefault() {

        mockAuthenticatedUser();

        when(addressRepository.findAllByUserIdOrderByIdDesc(1L))
                .thenReturn(List.of());

        when(addressRepository.save(any(Address.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        AddressResponseDTO response =
                addressService.createAddress(
                        "customer@example.com",
                        createRequest(false)
                );

        assertTrue(response.isDefault());
        assertEquals("Home", response.getLabel());

        verify(addressRepository).save(any(Address.class));
    }

    @Test
    void explicitlySelectedAddressShouldBecomeDefault() {

        mockAuthenticatedUser();

        Address existingDefault = createAddress(1L, true);

        when(addressRepository.findAllByUserIdOrderByIdDesc(1L))
                .thenReturn(List.of(existingDefault));

        when(addressRepository.save(any(Address.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        AddressResponseDTO response =
                addressService.createAddress(
                        "customer@example.com",
                        createRequest(true)
                );

        assertFalse(existingDefault.isDefault());
        assertTrue(response.isDefault());
    }

    @Test
    void deletingDefaultAddressShouldPromoteAnotherAddress() {

        mockAuthenticatedUser();

        Address addressToDelete = createAddress(10L, true);
        Address replacement = createAddress(11L, false);

        when(addressRepository.findByIdAndUserId(10L, 1L))
                .thenReturn(Optional.of(addressToDelete));

        when(addressRepository.findFirstByUserIdOrderByIdAsc(1L))
                .thenReturn(Optional.of(replacement));

        addressService.deleteAddress(
                "customer@example.com",
                10L
        );

        verify(addressRepository).delete(addressToDelete);
        verify(addressRepository).flush();

        assertTrue(replacement.isDefault());
    }


    @Test
    void customerCannotAccessAnotherCustomersAddress() {

        when(userRepository.findByEmail("customer@example.com"))
                .thenReturn(Optional.of(user));

        when(addressRepository.findByIdAndUserId(99L, 1L))
                .thenReturn(Optional.empty());

        assertThrows(
                org.springframework.web.server.ResponseStatusException.class,
                () -> addressService.getMyAddress(
                        "customer@example.com",
                        99L
                )
        );
    }

}
